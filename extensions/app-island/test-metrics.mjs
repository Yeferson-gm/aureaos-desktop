import assert from 'node:assert/strict';
import {cpuSnapshot, cpuUsage, memorySnapshot, networkSnapshot, networkRate, appendSample, calendarDays} from './metrics-model.js';
const a = cpuSnapshot('cpu 10 0 0 90 0 0 0 0 0 0');
const b = cpuSnapshot('cpu 20 0 0 100 0 0 0 0 0 0');
assert.equal(cpuUsage(a, b), 50);
assert.equal(cpuUsage(null, b), null);
assert.equal(cpuUsage(b, a), null);
assert.equal(cpuSnapshot('unavailable'), null);
const memory = memorySnapshot('MemTotal: 1000 kB\nMemAvailable: 400 kB\nCached: 200 kB\nSReclaimable: 50 kB\nSwapTotal: 200 kB\nSwapFree: 150 kB');
assert.equal(memory.used, 600 * 1024); assert.equal(memory.cached, 250 * 1024); assert.equal(memory.swap, 50 * 1024);
assert.equal(memorySnapshot(''), null);
const net = networkSnapshot('lo: 100 0 0 0 0 0 0 0 200\nwlan0: 1000 0 0 0 0 0 0 0 2000');
assert.equal(net.lo, undefined);
assert.deepEqual(networkRate(net, {wlan0: {rx: 3000, tx: 3000}, eth0: {rx: 9000, tx: 9000}}, 2), {rx: 1000, tx: 500});
assert.deepEqual(networkRate(net, {wlan0: {rx: 0, tx: 0}}, 2), {rx: 0, tx: 0});
assert.equal(networkRate(net, {}, 0), null);
assert.deepEqual(appendSample([1, 2], 3, 2), [2, 3]);
assert.deepEqual(appendSample([1, 2], null), [1, 2]);
assert.equal(calendarDays(new Date(2024, 1, 12)).filter(Boolean).length, 29);
console.log('PASS: CPU deltas, available memory, interface resets, bounded history and calendar');
