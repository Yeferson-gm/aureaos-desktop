d._query = 'm'; assert.equal(d._candidates().length, 0);
d._appSystem.get_installed = () => apps.map(a => ({get_id: a.get_id, should_show: () => true}));
d._query = 'musica'; assert.deepEqual(Array.from(d._candidates(), a => a.get_id()), ['b']);
assert.equal(d._items().length, 1);
d._onlyRunning = true; assert.equal(d._items().length, 0); apps[0].state = 1; assert.equal(d._items().length, 1);
