import assert from 'node:assert/strict';
import {controller} from './test-harness.mjs';
import {IslandModel, normalize} from './model.js';
const d = controller({normalize, Shell: {AppState: {RUNNING: 1}}});
d._model = new IslandModel({favoritos: ['a']});
const apps = [{get_id: () => 'a', get_name: () => 'Música'}, {get_id: () => 'b', get_name: () => 'Música nueva'}];
