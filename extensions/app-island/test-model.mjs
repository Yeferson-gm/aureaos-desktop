import assert from 'node:assert/strict';
import {IslandModel, preferences, migrate} from './model.js';
const m = new IslandModel({favoritos: ['a', 'b', 'a', 'missing']}, id => ({categories: id === 'a' ? 'Development;' : 'Utility;'}));
assert.equal(m.profile.items.length, 3);
assert.equal(m.profile.categories[0].name, 'Desarrollo');
assert.equal(m.profile.items[2].target, 'missing');
const category = m.category('Diseño');
m.move('a', category); assert.equal(m.profile.items.find(i => i.id === 'a').category, category);
assert.equal(m.category('diseno'), category);
m.remove('a'); assert.equal(m.profile.items.length, 2); m.restore(); assert.equal(m.profile.items.length, 3);
m.deleteCategory(category); assert(m.profile.items.every(i => m.profile.categories.some(c => c.id === i.category)));
m.profile.items[0].alias = 'Música'; assert.equal(m.filter('musica', () => '').length, 1);
assert.equal(m.add({...m.profile.items[0], id: 'duplicate'}), false);
m.newProfile('Trabajo'); assert.equal(m.profile.items.length, 0);
const restored = new IslandModel(JSON.parse(JSON.stringify(m.data))); assert.equal(restored.profile.name, 'Trabajo');
assert.equal(preferences({edge: -100, delay: 99999, theme: 'nonsense'}).edge, 1);
assert.equal(preferences({delay: 99999}).delay, 800);
assert.throws(() => migrate({format: 999, profiles: []}));
assert.throws(() => migrate(null));
console.log('PASS: migration, deduplication, categories, moves, undo, profiles, aliases and validated preferences');
