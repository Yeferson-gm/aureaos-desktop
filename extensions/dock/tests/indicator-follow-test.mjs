import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = fs.readFileSync(new URL('../appIconIndicators.js', import.meta.url), 'utf8');
const start = source.indexOf('class RunningIndicatorBase extends');
const end = source.indexOf('class RunningIndicatorDefault', start);
const context = vm.createContext({IndicatorBase: class {}, St: {Side: {BOTTOM: 0, TOP: 1, LEFT: 2, RIGHT: 3}}});
vm.runInContext(`${source.slice(start, end)};globalThis.Indicator = RunningIndicatorBase;`, context);
const indicator = Object.create(context.Indicator.prototype);
const visual = {translation_x: 24, translation_y: -20};
indicator._source = {icon: {_iconBin: visual}, _dot: {}};
indicator._area = {};
indicator._side = 0;
indicator._syncTranslation();
assert.equal(indicator._area.translation_x, 24);
assert.equal(indicator._source._dot.translation_x, 24);
assert.equal(indicator._area.translation_y, 0, 'Dot stays on shelf during bounce');
visual.translation_x = 0;
indicator._syncTranslation();
assert.equal(indicator._area.translation_x, 0);
indicator._side = 2;
indicator._syncTranslation();
assert.equal(indicator._area.translation_y, -20);
assert.equal(indicator._area.translation_x, 0);
console.log('PASS: dot follows lens on both axes without scaling or bounce');
