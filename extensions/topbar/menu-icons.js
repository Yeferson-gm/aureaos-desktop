export function iconFor(label, action = '', fallback = 'application-x-executable-symbolic') {
    const name = String(action).split('.').at(-1);
    if (Object.hasOwn(ACTION_ICONS, name)) return ACTION_ICONS[name];
    for (const [pattern, icon] of ICON_RULES)
        if (pattern.test(label ?? '')) return icon;
    return fallback;
}
