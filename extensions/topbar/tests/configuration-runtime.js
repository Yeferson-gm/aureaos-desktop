import Gio from 'gi://Gio';
import GLib from 'gi://GLib';
import {Config} from '../configuration.js';
const root = GLib.getenv('DI_TEST_DIR');
if (!root || !GLib.get_user_config_dir().startsWith(root + '/')) throw new Error('Requiere configuración aislada');
const config = new Config();
const loop = new GLib.MainLoop(null, false);
config.save({texto: 'claro', colorTexto: '#ffffff', customFutureOption: 'preservar'});
const file = Gio.File.new_for_path(config.path);
file.replace_contents(new TextEncoder().encode('{invalid'), null, false, Gio.FileCreateFlags.PRIVATE, null);
if (config.load() || config.values.colorTexto !== '#ffffff') throw new Error('JSON inválido reemplazó la configuración válida');
let changes = 0;
config.onChange(() => changes++);
file.replace_contents(new TextEncoder().encode('{"texto":"oscuro","modules":[],"customFutureOption":"preservar"}'), null, false, Gio.FileCreateFlags.PRIVATE, null);
GLib.timeout_add(GLib.PRIORITY_DEFAULT, 350, () => { loop.quit(); return GLib.SOURCE_REMOVE; });
loop.run();
if (config.values.texto !== 'oscuro' || config.values.modules.length || changes !== 1) throw new Error('No se recargó exactamente una sustitución atómica');
config.save({clockSeconds: true});
if (config.raw.customFutureOption !== 'preservar') throw new Error('Se eliminó una clave desconocida');
config.destroy();
file.delete(null);
print('PASS: JSON inválido conserva estado, reemplazo atómico recarga y claves futuras permanecen');
