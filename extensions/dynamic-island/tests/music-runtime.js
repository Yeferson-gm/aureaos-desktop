import Gio from 'gi://Gio';
import Clutter from 'gi://Clutter';
import GLib from 'gi://GLib';
import St from 'gi://St';
import Shell from 'gi://Shell';
import * as Main from 'resource:///org/gnome/shell/ui/main.js';

export async function testMusic(island, wait) {
    const assert = (condition, message) => { if (!condition) throw new Error(message); };
    const tools = island._musicTools;
    const fixture = Main.extensionManager.lookup('island-test-driver@local').stateObj.fixture;
    island._selectTab('music');
    island._openIsland();
    await wait(450);
    tools.star.emit('clicked', 1);
    assert(tools.isFavorite(), 'La estrella no guarda una favorita');
    const saved = JSON.parse(new TextDecoder().decode(tools.file.load_contents(null)[1]));
    assert(saved.length === 1 && saved[0].title === fixture.Metadata['xesam:title'].unpack(), 'Favorita no persistida');
    const {MusicTools} = await import(`file://${island.path}/music-tools.js`);
    assert(new MusicTools(island).favorites.length === 1, 'Favoritas no se restauran');
    island._shuffleBtn.button.emit('clicked', 1);
    await wait(180);
    assert(fixture.Shuffle === true && island._shuffle === true, 'Aleatorio no llega al reproductor');
    for (const expected of ['Playlist', 'Track', 'None']) {
        island._loopBtn.button.emit('clicked', 1);
        await wait(180);
        assert(fixture.LoopStatus === expected && island._loop === expected, 'Repetición no cicla los tres modos');
    }
    tools.moreButton.emit('clicked', 1);
    await wait(250);
    tools.rate.emit('clicked', 1);
    await wait(180);
    assert(fixture.Rate === 1.25 && tools.props.Rate === 1.25, 'Velocidad no se sincroniza');
    tools.forward.emit('clicked', 1);
    await wait(180);
    assert(fixture.Position === 45000000, 'Salto +15 no usa la posición del reproductor');
    island._seekTo(-15);
    await wait(180);
    assert(fixture.Position === 0, 'Seek negativo no se limita al inicio');
    island._seek.value = 0.5;
    await wait(180);
    assert(fixture.Position === 90000000, 'El deslizador sin arrastre no busca');
    const sink = island._sink;
    island._sink = null;
    tools.update(tools.props);
    island._muteButton.emit('clicked', 1);
    await wait(180);
    assert(fixture.Volume === 0 && island._volume.value === 0, 'Silencio MPRIS no sincroniza volumen');
    island._muteButton.emit('clicked', 1);
    await wait(180);
    assert(fixture.Volume === 0.6, 'Silencio no restaura el volumen anterior');
    island._sink = sink;
    island._syncVolume(false);
    island._seekDrag = true;
    island._seekTrackKey = 'another-track';
    island._seek.value = 0.9;
    island._seek.emit('drag-end');
    await wait(180);
    assert(fixture.Position === 90000000, 'Un arrastre antiguo busca en una canción nueva');
    island._readPosition();
    await wait(100);
    tools.panel.select('track');
    await wait(100);
    tools.raise.emit('clicked', 1);
    await wait(180);
    assert(fixture.raised, 'Abrir app no llama Raise');
    tools.copy.emit('clicked', 1);
    const clipboard = await new Promise(resolve => St.Clipboard.get_default().get_text(St.ClipboardType.CLIPBOARD, (_c, text) => resolve(text)));
    assert(clipboard === 'https://example.org/test-track', 'Copiar no conserva el enlace');
    tools.panel.select('playback');
    await wait(100);
    tools.stop.emit('clicked', 1);
    await wait(180);
    assert(island._status === 'Stopped', 'Detener no se refleja');
    island._command('PlayPause');
    await wait(180);
    fixture.Shuffle = false;
    fixture.LoopStatus = 'Track';
    island._refresh();
    await wait(180);
    assert(!island._shuffle && island._loopBtn.icon.icon_name === 'media-playlist-repeat-song-symbolic', 'Los cambios externos no se reflejan');
    tools.request('org.mpris.MediaPlayer2.Player', 'UnsupportedFixtureMethod');
    await wait(180);
    assert(tools.status.visible && tools.status.text.includes('no permite'), 'Error del reproductor sin respuesta visible');
    const props = tools.props;
    const currentTitle = props.Metadata['xesam:title'];
    tools.update({...props, CanControl: false});
    tools.command('Stop');
    await wait(80);
    assert(fixture.PlaybackStatus === 'Playing' && !tools.stop.reactive && !tools.back.reactive, 'Se ignoran capacidades de control');
    tools.update({...props, Rate: 1, MinimumRate: 1, MaximumRate: 1});
    assert(!tools.rate.reactive, 'Velocidad fija deja un botón activo');
    tools.update(props);
    tools.togglePanel('favorites');
    assert(tools.library.visible && !tools.more.visible && tools.favoriteRows.get_n_children() === 1, 'Biblioteca desordenada o vacía');
    const remove = tools.favoriteRows.get_first_child().get_last_child();
    remove.emit('clicked', 1);
    assert(!tools.favorites.length && !tools.isFavorite(), 'Retirar favorita no actualiza estrella');
    tools.togglePanel('favorites');
    tools.star.emit('clicked', 1);
    tools.message('');
    await wait(350);
    const capture = async name => {
        const stream = Gio.File.new_for_path(`${GLib.getenv('DI_TEST_DIR')}/${name}.png`).replace(null, false, Gio.FileCreateFlags.REPLACE_DESTINATION, null);
        await new Shell.Screenshot().screenshot(false, stream);
        stream.close(null);
    };
    assert(Math.abs(island._island.height - island._content.get_preferred_height(472)[1]) <= 2, 'Cerrar paneles deja altura antigua');
    const navigationBottom = tools.moreButton.get_transformed_position()[1] + tools.moreButton.height;
    assert(island._island.y + island._island.height - navigationBottom < 45, 'La vista musical deja espacio vacío excesivo');
    await capture('music-player');
    tools.togglePanel('more');
    await wait(350);
    await capture('music-more');
    const [panelX] = island._pageViewport.get_transformed_position();
    const [panelWidth] = island._pageViewport.get_transformed_size();
    for (const [section, actors] of [['playback', [tools.star, tools.stop, tools.forward, tools.rate, tools.shuffleRow, tools.repeatRow]],
        ['audio', [tools.output, tools.appAudio]], ['track', [tools.copy, tools.raise, island._mediaExtras.button]]]) {
        tools.panel.select(section); await wait(300);
        await capture(`music-options-${section}`);
        assert(Object.values(tools.panel.sections).filter(item => item.visible).length === 1, 'Se mezclan secciones del panel');
        for (const actor of actors) {
            const [x] = actor.get_transformed_position();
            const [width] = actor.get_transformed_size();
            assert(x >= panelX - 1 && x + width <= panelX + panelWidth + 1, `Control desborda la isla: ${actor.accessible_name}`);
        }
    }
    tools.panel.select('playback');
    const seat = global.stage.context.get_backend().get_default_seat();
    const pointer = seat.create_virtual_device(Clutter.InputDeviceType.POINTER_DEVICE);
    const click = async actor => {
        const [x, y] = actor.get_transformed_position(), [w, h] = actor.get_transformed_size();
        for (let attempt = 0; attempt < 10; attempt++) {
            pointer.notify_absolute_motion(GLib.get_monotonic_time(), x + w / 2, y + h / 2);
            await wait(35);
            const [px, py] = global.get_pointer();
            if (Math.abs(px - x - w / 2) < 2 && Math.abs(py - y - h / 2) < 2) break;
        }
        pointer.notify_button(GLib.get_monotonic_time(), Clutter.BUTTON_PRIMARY, Clutter.ButtonState.PRESSED);
        await wait(50);
        pointer.notify_button(GLib.get_monotonic_time(), Clutter.BUTTON_PRIMARY, Clutter.ButtonState.RELEASED);
        await wait(300);
    };
    await wait(300);
    await click(tools.repeatRow);
    assert(tools.repeatChoices.visible, 'El clic no abre opciones de repetición');
    await click(tools.repeatButtons.get('Track'));
    assert(fixture.LoopStatus === 'Track' && !tools.repeatChoices.visible, 'Elegir canción no activa repetición');
    await click(tools.panel.tabs.track);
    assert(tools.panel.sections.track.visible, 'La pestaña Canción no responde al clic');
    tools.panel.select('playback');
    const withoutShuffle = {...props}; delete withoutShuffle.Shuffle;
    tools.update(withoutShuffle);
    tools.shuffleRow.emit('clicked', 1);
    assert(tools.status.visible && tools.status.text.includes('aleatorio') && tools.shuffleRow._value.text === 'En la app', 'Shuffle ausente no explica la limitación');
    tools.update(props);
    fixture.LoopStatus = 'None';
    fixture.ignoreLoop = true;
    island._refresh(); await wait(150);
    island._loopBtn.button.emit('clicked', 1);
    assert(tools.repeatRow._value.text === 'Aplicando…' && !tools.repeatRow.reactive, 'Falta estado pendiente');
    await wait(700);
    assert(island._loop === 'None' && tools.unsupported.has('LoopStatus') && tools.repeatRow._value.text === 'En la app', 'La escritura ignorada simula éxito');
    assert(tools.status.text.includes('repetición') && !tools.propertyWrites.size, 'Repetición ignorada sin explicación o pendiente infinito');
    fixture.ignoreLoop = false;
    tools.unsupported.clear(); tools.update(props);
    tools.setProperty('LoopStatus', new GLib.Variant('b', true)); await wait(180);
    assert(tools.unsupported.has('LoopStatus') && !tools.propertyWrites.size, 'Error de escritura no libera pendiente');
    tools.unsupported.clear();
    tools.update(props); tools.message('');
    tools.update({});
    assert(!tools.star.reactive && !tools.copy.reactive, 'Sin pista todavía permite favoritos');
    tools.update(props);
    assert(tools.track.title === currentTitle, 'Pista no restaurada');
    tools.togglePanel('more');
    island._seekTo(30);
    fixture.LoopStatus = 'None'; fixture.Shuffle = false; fixture.Rate = 1;
    island._refresh();
    await wait(200);
    const name = island._name;
    island._usePlayer(null);
    assert(!island._playBtn.button.reactive && !tools.star.reactive && !tools.stop.reactive, 'Desconectar conserva acciones');
    island._usePlayer(name);
    assert(!island._playBtn.button.reactive && !tools.stop.reactive, 'Cambiar reproductor usa capacidades antiguas');
    await wait(250);
    assert(island._playBtn.button.reactive && tools.stop.reactive, 'El reproductor no recupera controles');
    island._closeIsland();
}
