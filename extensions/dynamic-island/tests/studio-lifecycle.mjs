import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync(new URL('../studio.js', import.meta.url), 'utf8');
const context = vm.createContext({});
vm.runInContext(source.replace(/^import .*;\n/gm, '').replace('export class', 'class') + '\nglobalThis.Studio = IslandStudio;', context);
const studio = new context.Studio({});
let finished;
let terminated = false;
const cleaned = [];
studio.clean = directory => cleaned.push(directory);
studio.directory = '/tmp/old-recording';
studio.transcribing = {force_exit() { terminated = true; }, wait_async(_cancel, callback) { finished = callback; }};
studio.recordButton = {_label: {text: ''}};
studio.status = {text: ''};
studio.toggleRecording();
assert.equal(terminated, true);
assert.equal(studio.transcribing, null);
studio.directory = '/tmp/new-recording';
finished();
assert.deepEqual(cleaned, ['/tmp/old-recording']);
assert.equal(studio.directory, '/tmp/new-recording');
console.log('Dictado: cancelar una transcripción anterior no elimina la grabación nueva.');
